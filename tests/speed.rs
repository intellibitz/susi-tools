//! End-to-end tests of `susi-tools speed` against a tiny throwaway Cargo workspace, so the suite
//! stays well under a second.

use std::path::{Path, PathBuf};
use std::process::Command;

#[path = "../src/git_program.rs"]
mod git_program;

struct WorkspaceFixture {
    root: PathBuf,
}

impl Drop for WorkspaceFixture {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.root);
    }
}

impl WorkspaceFixture {
    fn new(tag: &str, with_features: bool, lib_rs: &str) -> WorkspaceFixture {
        let root = std::env::temp_dir().join(format!(
            "susi-tools-speed-test-{tag}-{}",
            std::process::id()
        ));
        let _ = std::fs::remove_dir_all(&root);
        std::fs::create_dir_all(&root).unwrap();
        std::fs::write(
            root.join("gitconfig"),
            "[maintenance]\n\tauto = false\n[gc]\n\tauto = 0\n",
        )
        .unwrap();
        let fx = WorkspaceFixture { root };
        fx.git(
            &fx.root,
            &[
                "init",
                "-q",
                "--template=",
                "--bare",
                "-b",
                "main",
                "repo.git",
            ],
        );
        fx.git(
            &fx.root,
            &["init", "-q", "--template=", "-b", "main", "work"],
        );
        let bare = fx.bare();
        fx.git(
            &fx.work(),
            &["remote", "add", "origin", bare.to_str().unwrap()],
        );
        // Stand in for Susi so `susi-tools workflow check` reads the Board from `origin`.
        std::fs::write(fx.work().join(".susi-repo-role"), "private-commercial\n").unwrap();
        let mut manifest = String::from(
            "[package]\nname = \"tiny-speed-probe\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[profile.dev]\ndebug = 0\nincremental = false\n\n[profile.test]\ndebug = 0\nincremental = false\n",
        );
        if with_features {
            manifest.push_str("\n[features]\ndefault = [\"extra\"]\nextra = []\n");
        }
        std::fs::write(fx.work().join("Cargo.toml"), manifest).unwrap();
        std::fs::create_dir_all(fx.work().join("src")).unwrap();
        std::fs::write(fx.work().join("src/lib.rs"), lib_rs).unwrap();
        std::fs::write(
            fx.work().join("Cargo.lock"),
            "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 3\n\n[[package]]\nname = \"tiny-speed-probe\"\nversion = \"0.1.0\"\n",
        )
        .unwrap();
        fx.git(&fx.work(), &["add", "-A"]);
        fx.git(&fx.work(), &["commit", "-q", "-m", "fixture"]);
        fx.git(
            &fx.work(),
            &["push", "-q", bare.to_str().unwrap(), "HEAD:refs/heads/main"],
        );
        std::fs::create_dir_all(fx.target_dir()).unwrap();
        fx
    }

    fn bare(&self) -> PathBuf {
        self.root.join("repo.git")
    }

    fn work(&self) -> PathBuf {
        self.root.join("work")
    }

    fn target_dir(&self) -> PathBuf {
        self.root.join("agent-target")
    }

    fn git(&self, dir: &Path, args: &[&str]) -> String {
        let out = Command::new(git_program::path())
            .current_dir(dir)
            .env("GIT_CONFIG_GLOBAL", self.root.join("gitconfig"))
            .env("GIT_CONFIG_NOSYSTEM", "1")
            .args([
                "-c",
                "user.name=fixture",
                "-c",
                "user.email=fixture@example.test",
                "-c",
                "commit.gpgsign=false",
            ])
            .args(args)
            .output()
            .unwrap();
        assert!(
            out.status.success(),
            "git {args:?}: {}",
            String::from_utf8_lossy(&out.stderr)
        );
        String::from_utf8_lossy(&out.stdout).trim().to_owned()
    }

    fn run_speed(&self, extra_args: &[&str]) -> (i32, String, String) {
        let work = self.work();
        let out = Command::new(env!("CARGO_BIN_EXE_susi-tools"))
            .current_dir(&self.root)
            .env("GIT_CONFIG_GLOBAL", self.root.join("gitconfig"))
            .env("GIT_CONFIG_NOSYSTEM", "1")
            .env("SUSI_AGENT", "tester")
            .env("CARGO_TARGET_DIR", self.target_dir())
            .args(["speed", "--repo", work.to_str().unwrap()])
            .args(extra_args)
            .output()
            .unwrap();
        (
            out.status.code().unwrap_or(-1),
            String::from_utf8_lossy(&out.stdout).into_owned(),
            String::from_utf8_lossy(&out.stderr).into_owned(),
        )
    }
}

const GOOD_LIB: &str = "\
#[test]
fn tiny_probe_passes() {
    assert_eq!(2 + 2, 4);
}
";

#[test]
fn speed_table_times_every_operation_including_features() {
    let fx = WorkspaceFixture::new("table-features", true, GOOD_LIB);
    let src = fx.work().join("src/lib.rs");
    let before = std::fs::read(&src).unwrap();

    let (code, out, err) = fx.run_speed(&[]);
    assert_eq!(code, 0, "stdout:\n{out}\nstderr:\n{err}");
    assert!(out.contains("speed report for "), "{out}");
    assert!(
        out.contains("cargo build --workspace --offline --locked (nothing changed)"),
        "{out}"
    );
    assert!(
        out.contains("cargo build --workspace --offline --locked (touched src/lib.rs)"),
        "{out}"
    );
    assert!(
        out.contains("cargo nextest run --workspace --offline --locked --no-default-features"),
        "{out}"
    );
    assert!(
        out.contains("cargo clippy --workspace --all-targets --offline --locked -- -D warnings"),
        "{out}"
    );
    assert!(out.contains("cargo fmt --all --check"), "{out}");
    assert!(out.contains("git status"), "{out}");
    assert!(out.contains("git fetch"), "{out}");
    assert!(out.contains("susi-tools workflow check"), "{out}");
    assert!(!out.contains("Cold (reported apart"), "{out}");
    assert!(
        out.contains("9 of 9 warm operations under the 10.0s line"),
        "{out}"
    );
    assert_eq!(
        std::fs::read(&src).unwrap(),
        before,
        "touched file was not restored byte for byte"
    );
}

#[test]
fn speed_cold_json_reports_apart_and_keeps_agent_target() {
    let fx = WorkspaceFixture::new("cold-json", false, GOOD_LIB);
    let src = fx.work().join("src/lib.rs");
    let before = std::fs::read(&src).unwrap();
    // Sentinel inside the agent's own CARGO_TARGET_DIR: `--cold` must never clean it.
    let sentinel = fx.target_dir().join("agent-sentinel.txt");
    std::fs::write(&sentinel, b"untouched").unwrap();

    let (code, out, err) = fx.run_speed(&["--cold", "--json"]);
    assert_eq!(code, 0, "stdout:\n{out}\nstderr:\n{err}");
    assert!(
        out.starts_with('{') && out.trim_end().ends_with('}'),
        "{out}"
    );
    assert!(
        out.contains("\"schema\": \"susi-speed-report-v1\""),
        "{out}"
    );
    assert!(out.contains("\"touched_file\": \"src/lib.rs\""), "{out}");
    assert!(out.contains("\"has_features\": false"), "{out}");
    assert!(out.contains("\"warm_ok_under_line\": 8"), "{out}");
    assert!(out.contains("\"warm_total\": 8"), "{out}");
    assert!(out.contains("\"warm_over_line\": 0"), "{out}");
    assert!(out.contains("\"warm_failed\": 0"), "{out}");
    assert!(
        !out.contains("--no-default-features"),
        "should omit --no-default-features when workspace has no features:\n{out}"
    );
    assert!(
        out.contains("cargo build --workspace --offline --locked (cold, after cargo clean)"),
        "{out}"
    );
    assert_eq!(
        std::fs::read(&src).unwrap(),
        before,
        "touched file was not restored byte for byte"
    );
    assert_eq!(
        std::fs::read(&sentinel).unwrap(),
        b"untouched",
        "--cold cleaned the agent's own target directory"
    );
}

#[test]
fn speed_restores_touched_file_when_steps_fail() {
    // Deliberately broken + unformatted crate so cargo steps fail; touched file must still be
    // restored byte for byte.
    let broken = "pub fn bad(){let _x=1+;}";
    let fx = WorkspaceFixture::new("broken-restore", false, broken);
    let src = fx.work().join("src/lib.rs");
    let before = std::fs::read(&src).unwrap();

    let (code, out, err) = fx.run_speed(&["--json"]);
    assert_eq!(
        code, 1,
        "expected non-zero exit on broken crate: {out}\n{err}"
    );
    assert!(out.contains("\"has_features\": false"), "{out}");
    assert!(out.contains("\"warm_total\": 8"), "{out}");
    assert!(!out.contains("\"warm_failed\": 0"), "{out}");
    assert_eq!(
        std::fs::read(&src).unwrap(),
        before,
        "touched file was not restored byte for byte after failing steps"
    );
}

#[test]
fn speed_refuses_a_non_cargo_checkout() {
    let root =
        std::env::temp_dir().join(format!("susi-tools-speed-nocargo-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&root);
    std::fs::create_dir_all(&root).unwrap();
    let status = Command::new(git_program::path())
        .current_dir(&root)
        .args(["init", "-q", "--template=", "-b", "main"])
        .status()
        .unwrap();
    assert!(status.success());

    let out = Command::new(env!("CARGO_BIN_EXE_susi-tools"))
        .args(["speed", "--repo", root.to_str().unwrap()])
        .output()
        .unwrap();
    assert_eq!(out.status.code(), Some(2));
    let stderr = String::from_utf8_lossy(&out.stderr);
    assert!(stderr.contains("not a Cargo checkout"), "{stderr}");
    let _ = std::fs::remove_dir_all(&root);
}
