//! `local-harvest audit` (Susi Tools' rebuilt harvest audit) against made-up repositories: what
//! passes, what each rule refuses, and that retired records and citations are judged against
//! Git. The ledger format is Susi's (`susi-harvest-manifest-v1`).

use std::path::PathBuf;
use std::process::{Command, Output};

#[path = "../src/git_program.rs"]
mod git_program;

const APACHE: &str = "                                 Apache License\n                           Version 2.0, January 2004\n";
const COPYRIGHT: &str = "Copyright 2024 Upstream Authors";

struct Repo {
    root: PathBuf,
}

impl Drop for Repo {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.root);
    }
}

impl Repo {
    fn git(&self, args: &[&str]) -> String {
        let out = Command::new(git_program::path())
            .current_dir(&self.root)
            .env("GIT_CONFIG_GLOBAL", self.root.join(".git/fixture-global"))
            .env("GIT_CONFIG_NOSYSTEM", "1")
            .args([
                "-c",
                "user.name=fixture",
                "-c",
                "user.email=fixture@example.test",
                "-c",
                "commit.gpgsign=false",
                "-c",
                "core.autocrlf=false",
                // No background `git maintenance run` after commits: more processes for nothing.
                "-c",
                "maintenance.auto=false",
                "-c",
                "gc.auto=0",
            ])
            .args(args)
            .output()
            .unwrap();
        assert!(
            out.status.success(),
            "git {args:?}: {}",
            String::from_utf8_lossy(&out.stderr)
        );
        String::from_utf8_lossy(&out.stdout).trim().to_owned()
    }

    fn write(&self, rel: &str, text: &str) {
        let path = self.root.join(rel);
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, text).unwrap();
    }

    fn commit(&self, message: &str) -> String {
        self.git(&["add", "-A"]);
        self.git(&["commit", "-q", "-m", message]);
        self.git(&["rev-parse", "HEAD"])
    }

    fn audit(&self, args: &[&str]) -> Output {
        Command::new(env!("CARGO_BIN_EXE_local-harvest"))
            .current_dir(&self.root)
            .arg("audit")
            .args(args)
            .env_remove("LOCAL_HARVEST_LEGACY")
            .output()
            .unwrap()
    }
}

fn manifest(upstream: &str, blob: &str) -> String {
    format!(
        r#"{{
  "schema": "susi-harvest-manifest-v1",
  "id": "H-TEST-1",
  "task": "T-TEST-1",
  "feature": null,
  "source_url": "https://example.test/up.git",
  "source_commit": "{upstream}",
  "mode": "transplant",
  "license": "Apache-2.0",
  "files": [
    {{
      "copyright_lines": [],
      "source_blob_sha1": "{blob}",
      "source_path": "upstream/a.rs",
      "spdx": "Apache-2.0",
      "dest_path": "src/a.rs"
    }}
  ],
  "license_evidence": [],
  "license_texts": [],
  "notice_text": "",
  "copyright_lines": ["{COPYRIGHT}"],
  "harvested_by": "fixture",
  "harvested_unix": 1
}}
"#
    )
}

fn notices_header() -> String {
    "THIRD-PARTY NOTICES\n\nGenerated by `local-harvest notices` from .agents/harvest/*.json\n(susi-harvest-manifest-v1). Do not edit by hand; regenerate after every harvest.\nHarvested code keeps its upstream license. The Apache License 2.0 text is in\nLICENSES/Apache-2.0.txt.\n".to_owned()
}

fn notices(upstream: &str) -> String {
    format!(
        "{}\n{}\nH-TEST-1\nSource: https://example.test/up.git@{upstream}\nLicense: Apache-2.0\nFiles:\n  upstream/a.rs -> src/a.rs\nCopyright notices:\n  {COPYRIGHT}\n",
        notices_header(),
        "=".repeat(78)
    )
}

const SOURCE: &str = "// Copyright 2024 Upstream Authors\npub fn a() {}\n";

/// A repository whose first commit stands for the upstream and whose second harvests one file.
fn harvested(tag: &str) -> (Repo, String) {
    let root =
        std::env::temp_dir().join(format!("susi-tools-harvest-{tag}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&root);
    std::fs::create_dir_all(&root).unwrap();
    let repo = Repo { root };
    repo.git(&["init", "-q", "--template=", "-b", "main"]);
    repo.write("upstream/LICENSE", APACHE);
    repo.write("upstream/a.rs", SOURCE);
    let upstream = repo.commit("upstream");
    let blob = repo.git(&["rev-parse", &format!("{upstream}:upstream/a.rs")]);
    repo.write("src/a.rs", SOURCE);
    repo.write(".agents/harvest/H-TEST-1.json", &manifest(&upstream, &blob));
    repo.write("THIRD_PARTY_NOTICES", &notices(&upstream));
    repo.write("LICENSES/Apache-2.0.txt", APACHE);
    repo.git(&["add", "-A"]);
    repo.git(&[
        "commit",
        "-q",
        "-m",
        "harvest a.rs",
        "-m",
        "Harvest: H-TEST-1",
    ]);
    (repo, upstream)
}

fn text(out: &Output) -> String {
    format!(
        "{}{}",
        String::from_utf8_lossy(&out.stdout),
        String::from_utf8_lossy(&out.stderr)
    )
}

#[test]
fn a_clean_ledger_passes_and_counts_its_citation() {
    let (repo, _) = harvested("clean");
    let out = repo.audit(&["--range", "HEAD"]);
    assert!(out.status.success(), "{}", text(&out));
    assert_eq!(
        String::from_utf8_lossy(&out.stdout).trim(),
        "harvest audit passed: 1 manifest(s), 1 file(s), 1 Harvest-trailer commit(s); 0 retired record(s); 1 citation(s): 1 live, 0 retired, 0 corrected, 0 refused"
    );
    let json = repo.audit(&["--json"]);
    assert!(!json.status.success(), "--json is not an option of audit");
    assert!(
        text(&json).contains("unknown option --json for audit"),
        "{}",
        text(&json)
    );
}

#[test]
fn a_changed_file_needs_a_modified_by_notice() {
    let (repo, _) = harvested("modified");
    repo.write(
        "src/a.rs",
        "// Copyright 2024 Upstream Authors\npub fn a() { changed() }\n",
    );
    let out = repo.audit(&[]);
    assert!(!out.status.success());
    assert!(text(&out).contains("H-TEST-1: src/a.rs differs from upstream upstream/a.rs but has no \"Modified by\" notice (Apache-2.0 4(b))"), "{}", text(&out));
    repo.write("src/a.rs", "// Modified by the fixture.\n// Copyright 2024 Upstream Authors\npub fn a() { changed() }\n");
    assert!(repo.audit(&[]).status.success());
}

#[test]
fn an_upstream_copyright_line_must_stay() {
    let (repo, _) = harvested("copyright");
    repo.write("src/a.rs", "// Modified by the fixture.\npub fn a() {}\n");
    let out = repo.audit(&[]);
    assert!(!out.status.success());
    assert!(
        text(&out).contains(&format!(
            "H-TEST-1: src/a.rs lost upstream copyright line \"{COPYRIGHT}\" (Apache-2.0 4(c))"
        )),
        "{}",
        text(&out)
    );
}

#[test]
fn notices_must_be_exactly_what_the_manifests_render() {
    let (repo, _) = harvested("notices");
    repo.write("THIRD_PARTY_NOTICES", "hand-edited\n");
    let out = repo.audit(&[]);
    assert!(!out.status.success());
    assert!(text(&out)
        .contains("THIRD_PARTY_NOTICES is stale; run `local-harvest notices` (Apache-2.0 4(d))"));
    std::fs::remove_file(repo.root.join("LICENSES/Apache-2.0.txt")).unwrap();
    assert!(text(&repo.audit(&[]))
        .contains("LICENSES/Apache-2.0.txt is missing or not the Apache License 2.0 text"));
}

#[test]
fn a_destination_and_its_upstream_blob_must_both_be_there() {
    let (repo, upstream) = harvested("missing");
    std::fs::remove_file(repo.root.join("src/a.rs")).unwrap();
    assert!(text(&repo.audit(&[])).contains("H-TEST-1: destination src/a.rs is missing"));
    repo.write("src/a.rs", SOURCE);
    let wrong = "0".repeat(40);
    let blob = repo.git(&["rev-parse", &format!("{upstream}:upstream/a.rs")]);
    repo.write(
        ".agents/harvest/H-TEST-1.json",
        &manifest(&upstream, &blob).replace(&blob, &wrong),
    );
    assert!(text(&repo.audit(&[])).contains(&format!(
        "H-TEST-1: upstream/a.rs is not blob {wrong} at upstream {upstream}"
    )));
}

#[test]
fn a_citation_nothing_answers_is_refused() {
    let (repo, _) = harvested("citation");
    repo.write("src/b.txt", "b\n");
    repo.git(&["add", "-A"]);
    repo.git(&[
        "commit",
        "-q",
        "-m",
        "cite a missing harvest",
        "-m",
        "Harvest: H-TEST-9",
    ]);
    let out = repo.audit(&["--range", "HEAD"]);
    assert!(!out.status.success());
    let all = text(&out);
    assert!(all.contains("has `Harvest: H-TEST-9` but .agents/harvest/H-TEST-9.json does not exist and no valid .agents/harvest/retired/H-TEST-9.json stands for it"), "{all}");
    assert!(
        all.contains("2 citation(s): 1 live, 0 retired, 0 corrected, 1 refused"),
        "{all}"
    );
    // Without a range no history is read.
    assert!(repo.audit(&[]).status.success());
}

#[test]
fn a_removed_harvest_is_retired_with_its_commit_and_date() {
    let (repo, upstream) = harvested("retired");
    let blob = repo.git(&["rev-parse", &format!("{upstream}:upstream/a.rs")]);
    std::fs::remove_file(repo.root.join("src/a.rs")).unwrap();
    std::fs::remove_file(repo.root.join(".agents/harvest/H-TEST-1.json")).unwrap();
    repo.write(
        "THIRD_PARTY_NOTICES",
        &format!("{}\nNo harvested third-party code.\n", notices_header()),
    );
    let removal = repo.commit("remove a.rs");
    // History shows the manifest deleted: it must come back as a retired record.
    let out = repo.audit(&["--range", "HEAD"]);
    assert!(
        text(&out).contains(
            ".agents/harvest/H-TEST-1.json was removed from the ledger without being retired"
        ),
        "{}",
        text(&out)
    );
    let date = repo.git(&["log", "-1", "--format=%cs", &removal]);
    let record = |date: &str| {
        manifest(&upstream, &blob).trim_end().trim_end_matches('}').trim_end().to_owned()
            + &format!(",\n  \"retired\": {{\"removed_on\": \"{date}\", \"removed_by_commit\": \"{removal}\", \"reason\": \"The fixture no longer needs it.\"}}\n}}\n")
    };
    repo.write(".agents/harvest/retired/H-TEST-1.json", &record(&date));
    repo.commit("retire H-TEST-1");
    let out = repo.audit(&["--range", "HEAD"]);
    assert!(out.status.success(), "{}", text(&out));
    assert!(
        text(&out).contains("1 retired record(s); 1 citation(s): 0 live, 1 retired"),
        "{}",
        text(&out)
    );
    repo.write(
        ".agents/harvest/retired/H-TEST-1.json",
        &record("1999-01-01"),
    );
    let out = repo.audit(&[]);
    assert!(
        text(&out).contains(&format!(
            "removed_on 1999-01-01 is not the date of {removal} ({date})"
        )),
        "{}",
        text(&out)
    );
}

#[test]
fn other_commands_go_to_the_earlier_program() {
    let out = Command::new(env!("CARGO_BIN_EXE_local-harvest"))
        .arg("notices")
        .env_remove("LOCAL_HARVEST_LEGACY")
        .env("PATH", std::env::temp_dir())
        .output()
        .unwrap();
    assert_eq!(out.status.code(), Some(2));
    assert!(String::from_utf8_lossy(&out.stderr).contains("only `audit` is rebuilt"));
}
